import pandas as pd
import re
from urllib.parse import urlparse

def get_brand_from_url(url):
    if pd.isna(url):
        return "Unknown"

    parts = urlparse(str(url)).path.strip("/").split("/")
    if parts and parts[0]:
        return parts[0].replace("-", " ").title()

    return "Unknown"


def analyse_stockouts(df, lost_sales_per_size=1):
    data = df.copy()

    # Extract brand from product URL
    data["brand"] = data["url"].apply(get_brand_from_url)

    # Convert price to numeric
    data["price"] = pd.to_numeric(
        data["price"].astype(str).str.replace(r"[£,]", "", regex=True),
        errors="coerce"
    )

    # Extract sizes explicitly marked as out of stock
    def extract_stockouts(size_text):
        if pd.isna(size_text):
            return []

        pattern = r"([^,]+?)\s*-\s*Out of\s+stock"
        matches = re.findall(pattern, str(size_text), flags=re.IGNORECASE)

        return [size.strip() for size in matches]

    data["out_of_stock_sizes"] = data["size"].apply(extract_stockouts)

    # Count unavailable sizes for each product
    data["stockout_count"] = data["out_of_stock_sizes"].apply(len)

    # Estimate potential revenue opportunity
    data["phantom_revenue"] = (
        data["price"].fillna(0)
        * data["stockout_count"]
        * lost_sales_per_size
    )

    # Aggregate results by brand
    brand_summary = (
        data.groupby("brand")
        .agg(
            total_products=("url", "count"),
            products_with_stockouts=(
                "stockout_count",
                lambda x: (x > 0).sum()
            ),
            unavailable_size_count=("stockout_count", "sum"),
            estimated_phantom_revenue=("phantom_revenue", "sum")
        )
        .sort_values(
            "estimated_phantom_revenue",
            ascending=False
        )
        .reset_index()
    )

    return data, brand_summary

product_analysis, brand_summary = analyse_stockouts(df)

